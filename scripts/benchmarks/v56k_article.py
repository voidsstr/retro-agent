#!/usr/bin/env python3
"""
v56k_article.py - emit the article-ready data section from results.csv.

The numbers in docs/specpicks-voodoo5-6000.md are GENERATED by this, for the
same reason docs/fleet-inventory.md and docs/staged-library.md are generated:
a hand-copied benchmark table goes stale the moment another cell is measured,
and a stale table in an editorial piece is worse than no table.

    python3 v56k_article.py [results.csv] > data-section.md

It prints, in order:
  * provenance - box, driver, renderer strings actually recorded per run
  * the fps grid, config x resolution
  * SLI scaling vs one chip, per resolution
  * the cost of AA at a fixed chip count
  * every NOT-MEASURED cell with its reason

That last section is not filler. A blank cell that reads as a pass is how a
benchmark table starts lying, and on this card several cells are legitimately
unmeasurable (a mode the driver refuses, a config that wedged the board). They
are named, with the reason, rather than omitted.
"""

import csv
import sys
from collections import OrderedDict
from pathlib import Path

CHIPS = {0: 1, 1: 1, 2: 2, 3: 2, 4: 2, 5: 4, 6: 4, 7: 4, 8: 4}
SAMPLES = {0: 1, 1: 2, 2: 1, 3: 2, 4: 4, 5: 1, 6: 2, 7: 4, 8: 8}
# The DRIVER's own labels for each SSTH3_SLI_AA_CONFIGURATION value, quoted.
# They are what 3dfx Tools shows; they are NOT established descriptions of what
# the card does - cfg 2 ("Dual Chip") scales 3.47x over cfg 0 and beats cfg 5
# ("Quad Chip") at every resolution, so a table that printed "2 chips" would be
# asserting a chip count the measurement contradicts. Print the setting and the
# driver's words, and let the reader see the quote marks.
LABEL = {0: 'cfg 0 "Single Chip Only"', 1: 'cfg 1 "Single Chip, 2-Sample AA"',
         2: 'cfg 2 "Dual Chip, Fastest Performance"', 3: 'cfg 3 "Dual Chip, 2-Sample AA"',
         4: 'cfg 4 "Dual Chip, 4-Sample AA"', 5: 'cfg 5 "Quad Chip, Fastest Performance"',
         6: 'cfg 6 "Quad Chip, 2-Sample AA"', 7: 'cfg 7 "Quad Chip, 4-Sample AA"',
         8: 'cfg 8 "Quad Chip, 8-Sample AA"'}


def load(p):
    with open(p, newline="") as fh:
        return list(csv.DictReader(fh))


def fnum(v):
    try:
        return float(v)
    except (TypeError, ValueError):
        return None


def main():
    path = sys.argv[1] if len(sys.argv) > 1 else str(
        Path(__file__).resolve().parent / "results" / "v56k_192.168.1.191" / "results.csv")
    rows = load(path)
    ok = [r for r in rows if r["status"] == "ok" and fnum(r["avg_fps"])]

    # resolutions in pixel order, configs in chip/AA order
    res = sorted({(int(r["width"]), int(r["height"])) for r in ok},
                 key=lambda wh: wh[0] * wh[1])
    cfgs = sorted({int(r["aa_cfg"]) for r in ok})
    grid = {}
    for r in ok:
        grid[(int(r["aa_cfg"]), (int(r["width"]), int(r["height"])))] = fnum(r["avg_fps"])

    print("<!-- GENERATED by scripts/benchmarks/v56k_article.py - do not hand-edit -->")
    print(f"<!-- source: {path} ; {len(ok)} measured cell(s) of {len(rows)} -->\n")

    # ---- provenance ---------------------------------------------------- #
    print("### Provenance\n")
    rends = sorted({r["gl_renderer"] for r in ok if r.get("gl_renderer")})
    engines = sorted({r["engine"] for r in ok if r.get("engine")})
    unver = [r for r in rows if r.get("aa_verified", "").startswith("NO")]
    print(f"- engine: {', '.join(engines) or 'n/a'}")
    for x in rends:
        print(f"- renderer recorded on every run: `{x}`")
    if len(rends) > 1:
        print("- **WARNING: more than one renderer appears in this data; the rows "
              "do not all describe the same driver.**")
    print(f"- AA config written and read back on every measured row: "
          f"{'yes' if not unver else f'NO - {len(unver)} row(s) did not even write'}")
    print("- **but a value that reads back is not a card that anti-aliases.** "
          "Measured on this box: requesting 4x AA produced a BYTE-IDENTICAL "
          "Quake III frame (same md5, zero pixel difference) and no fps cost "
          "at all. Each AA row below is therefore checked against its matching "
          "no-AA cell, and one that costs nothing is reported as AA NOT "
          "APPLIED rather than as a free feature.")
    print()

    # ---- the grid ------------------------------------------------------ #
    print("### Average fps, Quake III `demo four`, 16-bit\n")
    print("| configuration | " + " | ".join(f"{w}x{h}" for w, h in res) + " |")
    print("|---|" + "|".join(["--:"] * len(res)) + "|")
    for c in cfgs:
        cells = [f"{grid[(c,r)]:.1f}" if (c, r) in grid else "–" for r in res]
        print(f"| **{LABEL.get(c, c)}** | " + " | ".join(cells) + " |")
    print()

    # ---- SLI scaling --------------------------------------------------- #
    base = {r: grid.get((0, r)) for r in res}
    if any(base.values()):
        print("### Spread against cfg 0 (the driver's \"Single Chip Only\" setting)\n")
        print("| resolution | cfg 0 | cfg 2 | cfg 5 | cfg 2 ÷ cfg 0 | cfg 5 ÷ cfg 0 |")
        print("|---|--:|--:|--:|--:|--:|")
        for r in res:
            c1, c2, c4 = grid.get((0, r)), grid.get((2, r)), grid.get((5, r))
            row = [f"{r[0]}x{r[1]}",
                   f"{c1:.1f}" if c1 else "–",
                   f"{c2:.1f}" if c2 else "–",
                   f"{c4:.1f}" if c4 else "–",
                   f"{c2/c1:.2f}x" if c1 and c2 else "–",
                   f"{c4/c1:.2f}x" if c1 and c4 else "–"]
            print("| " + " | ".join(row) + " |")
        print()

    # ---- cost of AA at a fixed chip count ------------------------------ #
    for chips, trio in ((4, (5, 6, 7, 8)), (2, (2, 3, 4)), (1, (0, 1))):
        if not any((c, r) in grid for c in trio for r in res):
            continue
        head = [f"{SAMPLES[c]}x AA" if SAMPLES[c] > 1 else "no AA" for c in trio]
        print(f"### Cost of requested anti-aliasing within the driver's "
              f"{'quad' if chips == 4 else 'dual' if chips == 2 else 'single'}-chip group"
              f"  (% of the no-AA figure retained)\n")
        print("| resolution | " + " | ".join(head) + " |")
        print("|---|" + "|".join(["--:"] * len(trio)) + "|")
        for r in res:
            b = grid.get((trio[0], r))
            cells = []
            for c in trio:
                v = grid.get((c, r))
                if not v:
                    cells.append("–")
                elif c == trio[0]:
                    cells.append(f"{v:.1f}")
                else:
                    if not b:
                        cells.append(f"{v:.1f}")
                    else:
                        pct = v / b * 100
                        # A sample count above 1 that costs under 3% has not
                        # been applied: AA is a fill-rate cost by construction,
                        # so "free AA" is a measurement of AA being ignored.
                        flag = " **not applied**" if pct > 97 else ""
                        cells.append(f"{v:.1f} ({pct:.0f}%){flag}")
            print(f"| {r[0]}x{r[1]} | " + " | ".join(cells) + " |")
        print()
        print("A cell marked **not applied** retained ≥97% of the no-AA frame "
              "rate. Anti-aliasing costs fill rate by construction, so a free "
              "AA cell is evidence the setting never reached the hardware - "
              "confirmed independently here by byte-identical screenshots.")
        print()

    # ---- what is NOT measured, and why --------------------------------- #
    bad = [r for r in rows if r["status"] != "ok"]
    print("### Cells not measured, with the reason\n")
    if not bad:
        print("None - every attempted cell produced a verified number.\n")
    else:
        print("| configuration | resolution | status | note |")
        print("|---|---|---|---|")
        for r in bad:
            try:
                c = int(r["aa_cfg"])
            except ValueError:
                c = r["aa_cfg"]
            note = (r.get("notes") or "")[:80]
            print(f"| {LABEL.get(c, c)} | {r['res']} | `{r['status']}` | {note} |")
        print()
    return 0


if __name__ == "__main__":
    sys.exit(main())
