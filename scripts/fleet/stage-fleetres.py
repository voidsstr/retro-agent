def idtech3_cfg(mod, wide=True, fov=True):
    """The cfg the staged autoexec.cfg execs, written fresh at every launch.

    r_mode / r_customwidth / r_customheight / r_fullscreen are CVAR_LATCH: they
    bite only at renderer init. The staged autoexec.cfg used to `seta r_mode 6`
    there, which beat the command line on .123. That seta is now gone from the
    library and `exec fleetres.cfg` is the LAST line of autoexec.cfg instead, so
    whatever the box's own config wrote earlier is overridden in the same pass.
    """
    w, h = ("%FR_W%", "%FR_H%") if wide else ("%FR_W43%", "%FR_H43%")
    p = '"%%~dp0%s\\fleetres.cfg"' % mod
    lines = [
        '> %s echo // written by the launcher at every start - do not edit' % p,
        '>>%s echo seta r_mode "-1"' % p,
        '>>%s echo seta r_customwidth "%s"' % (p, w),
        '>>%s echo seta r_customheight "%s"' % (p, h),
        '>>%s echo seta r_customaspect "1"' % p,
        '>>%s echo seta r_customPixelAspect "1"' % p,
        '>>%s echo seta r_fullscreen "1"' % p,
        # THE REFRESH RATE, and FR_HZ rather than a constant: a hardcoded 60
        # throws away 100 Hz on .143, 85 on .133 and 75 on .124. r_displayRefresh
        # is present in every id Tech 3 binary in this library (checked: quake3,
        # ioquake3, jasp, sof2mp, WolfSP), and 0 means "driver default", so it is
        # safe on a box whose rate could not be read.
        #
        # THE AGENT WRITES THIS SAME FILE (agent/shared/gameres.h, GAMERES), and
        # both writers MUST emit the same number or each rewrites the other's
        # copy on every launch and every sync. That is why this is FR_HZ - the
        # persisted desktop rate - and not the highest rate the panel offers at
        # the target. The agent raises the DESKTOP to the panel's best refresh
        # instead, which makes FR_HZ that best rate for everything at once,
        # including the engines with no refresh setting of their own.
        '>>%s echo seta r_displayRefresh "%%FR_HZ%%"' % p,
    ]
    # fov=False is RTCW: verified at 1920x1080 on .240 WITHOUT a cg_fov line,
    # and the default 90 there is vert- at 16:9 - a cg_fov value for it is an
    # untested, optional follow-up, not something to ship blind.
    if wide and fov:
        # id Tech 3 is vert-: at 16:9 with the default FOV you see LESS
        # vertically, not more horizontally. FR_FOV restores the 4:3 vertical
        # field of view (106 at 16:9, 90 at 4:3).
        lines.append('>>%s echo seta cg_fov "%%FR_FOV%%"' % p)
    return lines


def idtech3_modecfg(mod, fov=True):
    """For an id Tech 3 fork with NO r_mode -1 BRANCH.

    NO TITLE USES THIS TODAY (2026-09-29): the two forks it was written for,
    SoF2 and RTCW, turned out to have the branch - see IDTECH3_NO_CUSTOM_MODE.
    The 640x480 described below was sof2mp.exe's r_mode MINIMUM of 3.0, which
    the staged exe is now patched past. Kept for a fork that really lacks it.

    `r_mode -1` + r_customwidth/r_customheight is the standard idiom and it is
    NOT universal: measured on .145 with an identical fleetres.cfg,
    quake3.exe/jasp.exe/jamp.exe all came up at 1920x1080 and **sof2mp.exe came
    up at 640x480**. It does not error - it renders small - which is exactly
    the silent class of defect this repo keeps paying for.

    So this fork gets a plain mode INDEX, and it must be FR_Q3MODE and not
    FR_Q2MODE: the two engines' tables differ at index 8, which is 1280x960
    (4:3) in id Tech 2 and 1280x1024 (5:4) in id Tech 3. Asking a 16:9 panel
    for 1280x1024 is the squashed picture this whole mechanism removes."""
    p = '"%%~dp0%s\\fleetres.cfg"' % mod
    out = [
        '> %s echo // written by the launcher at every start - do not edit' % p,
        '>>%s echo // r_mode -1 DOES NOT EXIST IN THIS ENGINE - a plain index,' % p,
        '>>%s echo // and FR_Q3MODE not FR_Q2MODE: idTech3 mode 8 is 1280x1024.' % p,
        '>>%s echo seta r_mode "%%FR_Q3MODE%%"' % p,
        '>>%s echo seta r_fullscreen "1"' % p,
        # See idtech3_cfg(): FR_HZ, and the agent writes the same line.
        '>>%s echo seta r_displayRefresh "%%FR_HZ%%"' % p,
    ]
    # FR_FOV is computed for the PANEL, and every entry in this engine's mode
    # table except 11 is 4:3. So a title that renders at a mode INDEX is
    # rendering 4:3 and wants the engine's own 90, not the 106 a 16:9 panel
    # would earn - handing it 106 widens an already-correct picture. Left True
    # by default so the titles that already ship it are not changed silently.
    if fov:
        out.append('>>%s echo seta cg_fov "%%FR_FOV%%"' % p)
    return out


