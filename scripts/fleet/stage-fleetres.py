#!/usr/bin/env python3
"""Stage the per-box resolution helper (FLEETRES) into the staged game library.

WHY THIS EXISTS. One staged tree deploys to eight machines with eight different
monitors — four 1920x1080 LCDs and four CRTs, two of which are 4:3 tubes being
driven at 5:4. A resolution written into a staged config is therefore wrong
somewhere **by construction**, and every title in the library was pinned at
1024x768 (Tiberian Sun at 640x480).

The fix has to stay INSIDE the staged tree, or it dies at the next re-image and
the next GAMESYNC overwrites it — that already happened once, to a hand-edited
baseq3\\autoexec.cfg on .123. So the fix is runtime: every title's launcher runs
FLEETRES.EXE, staged beside it, which reads THIS box's panel and writes the
game's own config (or command line) before the game starts.

    python3 scripts/fleet/stage-fleetres.py            # apply
    python3 scripts/fleet/stage-fleetres.py --dry-run  # show what would change
    python3 scripts/fleet/stage-fleetres.py --check    # exit 1 if not applied

It is idempotent: a launcher that already carries the block is left alone. Every
transformation asserts that it actually matched — a silent no-op here would
present as "the resolution fix does not work on that title", days later, on a
box, which is exactly the failure mode this repo keeps paying for.
"""

