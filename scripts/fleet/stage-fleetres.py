def _d2_dosbox(kind):
    """Descent II's DOSBox lane: Play, Host or Join - the Descent 1 pattern v2."""
    head = ["@echo off",
            "rem Descent II - the DOS game in the staged DOSBox%s."
            % {"play": "", "host": " - HOST a LAN game",
               "join": " - JOIN a LAN game"}[kind],
            "rem Generated by retro-agent scripts/fleet/stage-fleetres.py - fix it there.",
            "rem   [fleet DOSBox LAN pattern v2, the same as Descent 1]",
            "rem",
            "rem  The original engine - v1.2 with Vertigo - beside the DXX-Rebirth",
            "rem  default. It is the Descent II that can meet the DOS game over IPX:",
            "rem  Rebirth 0.58.1 speaks UDP/IP only. DESCENT2.EXE is the no-CD build.",
            "rem  cd into DOSBOX first so the conf's relative mount C .. resolves",
            "rem  wherever the tree lands. Cycles are capped in dosboxD2.conf, or",
            "rem  Descent runs too fast on a fast box - see that file."]
    if kind == "host":
        head += [
            "rem",
            "rem  ipx=true only enables DOSBox's emulated adapter. Exactly ONE machine",
            "rem  runs IPXNET STARTSERVER - this shortcut - and every other machine runs",
            "rem  IPXNET CONNECT to it: Join Descent 2 - DOSBox LAN.",
            "echo.",
            "echo  Other players need THIS machine's address:",
            IPCONFIG_LINE,
            "echo.",
            "echo  On every other machine: put that address in C:\\Games\\lanhost.txt and run",
            'echo  "Join Descent 2 - DOSBox LAN".',
            "echo.",
        ]
    if kind == "join":
        head += [
            "rem",
            "rem  WHERE THE HOST ADDRESS COMES FROM - first one that exists wins:",
            "rem    1. the first argument to this .bat",
            "rem    2. lanhost.txt beside this file        - per-title override",
            "rem    3. C:\\Games\\lanhost.txt                - fleet-wide, one line",
            "rem    4. only then, ask at the console",
            "rem  FOUR CONNECT ATTEMPTS: DOSBox's IPX client gives up after 5 s and runs",
            "rem  the game anyway, so a joiner that beat the host to STARTSERVER lands",
            "rem  in the netgame list with no tunnel - measured with Descent 1.",
            "setlocal",
            'set "HOSTIP=%~1"',
            'if not defined HOSTIP if exist "%~dp0lanhost.txt" for /f "usebackq eol=; '
            'tokens=1 delims= " %%A in ("%~dp0lanhost.txt") do if not defined HOSTIP '
            'set "HOSTIP=%%A"',
            'if not defined HOSTIP if exist "C:\\Games\\lanhost.txt" for /f "usebackq '
            'eol=; tokens=1 delims= " %%A in ("C:\\Games\\lanhost.txt") do if not '
            'defined HOSTIP set "HOSTIP=%%A"',
            'if not defined HOSTIP set /p "HOSTIP=IP address of the machine hosting the game: "',
            "if not defined HOSTIP (",
            "    echo.",
            "    echo  No host address given - nothing to join.",
            "    echo  Put the host machine's IP on the first line of C:\\Games\\lanhost.txt",
            "    echo  and run this shortcut again.",
            "    ping -n 6 127.0.0.1 >nul",
            "    exit",
            ")",
            "echo  Joining the IPX tunnel on %HOSTIP% ...",
            'set "JC=%TEMP%\\ipxjoin_D2.conf"',
            '> "%JC%" echo [IPX]',
            '>>"%JC%" echo ipx=true',
            '>>"%JC%" echo.',
            '>>"%JC%" echo [autoexec]',
            '>>"%JC%" echo IPXNET CONNECT %HOSTIP%',
            '>>"%JC%" echo IPXNET CONNECT %HOSTIP%',
            '>>"%JC%" echo IPXNET CONNECT %HOSTIP%',
            '>>"%JC%" echo IPXNET CONNECT %HOSTIP%',
        ]
    middle = ([CALL] + dosbox_conf("dosboxD2.conf") + D2_SOUND_RESTORE
              + ["", 'cd /d "%~dp0DOSBOX"'])
    confs = {"play": '-conf "..\\dosboxD2.conf" -conf "..\\dosboxD2_single.conf"',
             "host": '-conf "..\\dosboxD2.conf" -conf "..\\_ipxhost.conf" '
                     '-conf "..\\dosboxD2_single.conf"',
             "join": '-conf "..\\dosboxD2.conf" -conf "%JC%" '
                     '-conf "..\\dosboxD2_single.conf"'}[kind]
    tail = ["DOSBox.exe " + confs, "",
            "rem Close this console - a launcher that lingers stacks a window per",
            "rem launch and makes every later screenshot ambiguous."]
    tail += ["endlocal", "exit"] if kind == "join" else ["exit"]
    return "\n".join(head + middle + tail) + "\n"


