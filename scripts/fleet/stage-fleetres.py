def read(path):
    with open(path, "rb") as fh:
        return fh.read().decode("latin1")


def write(path, text):
    with open(path, "wb") as fh:
        fh.write(text.encode("latin1"))


def crlf(text):
    return text.replace("\r\n", "\n").replace("\n", "\r\n")


class Runner:
    def __init__(self, lib, dry, check):
        self.lib, self.dry, self.check = lib, dry, check
        self.changed, self.errors, self.skipped = [], [], 0

    def note(self, what):
        self.changed.append(what)

    def fail(self, what):
        self.errors.append(what)

    def put(self, path, text, what):
        """Write only if the content differs — and say so."""
        if os.path.isfile(path) and read(path) == text:
            self.skipped += 1
            return False
        if self.check:
            self.fail("%s: not staged" % what)
            return False
        if not self.dry:
            write(path, text)
        self.note(what)
        return True

    # ---- the per-title steps -------------------------------------------
    def payload(self, tdir, title):
        src = os.path.join(PAYLOAD, "FLEETRES.EXE")
        dst = os.path.join(tdir, "FLEETRES.EXE")
        want = open(src, "rb").read()
        if not os.path.isfile(dst) or open(dst, "rb").read() != want:
            if self.check:
                self.fail("%s: FLEETRES.EXE not staged" % title)
            else:
                if not self.dry:
                    shutil.copyfile(src, dst)
                self.note("%s/FLEETRES.EXE" % title)
        else:
            self.skipped += 1
        self.put(os.path.join(tdir, "FLEETRES.BAT"), crlf(FLEETRES_BAT),
                 "%s/FLEETRES.BAT" % title)

    def patch_launcher(self, tdir, title, name, r):
        path = os.path.join(tdir, name)
        if not os.path.isfile(path):
            self.fail("%s/%s: launcher missing from the library" % (title, name))
            return
        body = read(path)
        if MARK in body:
            self.skipped += 1
            return
        if self.check:
            self.fail("%s/%s: no FLEETRES block" % (title, name))
            return

        nl = "\r\n" if "\r\n" in body else "\n"
        flat = body.replace("\r\n", "\n")

        anchor = r["before"]
        if anchor not in flat:
            self.fail("%s/%s: anchor %r not found — the launcher changed "
                      "under us, so this recipe is stale" % (title, name, anchor))
            return
        block = "\n".join(r["pre"])
        flat = flat.replace(anchor, block + "\n\n" + anchor, 1)

        if r["sub"]:
            pat, repl = r["sub"]
            new, n = re.subn(pat, lambda m: repl, flat, count=1)
            if n != 1:
                self.fail("%s/%s: launch-line pattern matched %d times, not 1 "
                          "— refusing to ship a launcher that silently did not "
                          "get its resolution arguments" % (title, name, n))
                return
            flat = new

        out = flat.replace("\n", nl) if nl == "\r\n" else flat
        if not self.dry:
            write(path, out)
        self.note("%s/%s" % (title, name))

    def repair(self, tdir, title, name, pairs):
        """Change a launcher this tool has ALREADY staged.

        patch_launcher keys idempotency off the presence of `FLEETRES.BAT`, so
        once a launcher carries the block it is never touched again — which is
        right for re-runs and wrong the day a recipe changes. Every repair here
        is a literal old->new pair that must be in exactly one of two states:
        present (apply it) or already applied (skip). NEITHER is an error, not
        a silent no-op, because "the recipe no longer matches the library" is
        precisely the condition that ships a launcher which did not get its
        arguments."""
        path = os.path.join(tdir, name)
        if not os.path.isfile(path):
            self.fail("%s/%s: launcher missing from the library" % (title, name))
            return
        body = read(path)
        out = body
        did = []
        for old, new in pairs:
            if old in out:
                if self.check:
                    self.fail("%s/%s: still has %r" % (title, name, old))
                    return
                out = out.replace(old, new)
                did.append(old)
            elif new not in out:
                self.fail("%s/%s: neither %r nor its replacement is present — "
                          "this recipe is stale, and applying it blind would "
                          "ship a launcher that silently did not change"
                          % (title, name, old))
                return
        if not did:
            self.skipped += 1
            return
        if not self.dry:
            write(path, out)
        self.note("%s/%s [repair]" % (title, name))

    def post_block(self, tdir, title, pb):
        """A second, independently-marked block in a launcher that may ALREADY
        carry the FLEETRES block. patch_launcher keys idempotency off
        `FLEETRES.BAT`, so it skips a launcher it has already done - which would
        silently drop anything added later. This one keys off its own marker."""
        path = os.path.join(tdir, pb["file"])
        if not os.path.isfile(path):
            self.fail("%s/%s: launcher missing from the library"
                      % (title, pb["file"]))
            return
        body = read(path)
        if pb["marker"] in body:
            self.skipped += 1
            return
        if self.check:
            self.fail("%s/%s: no %s block" % (title, pb["file"], pb["marker"]))
            return
        nl = "\r\n" if "\r\n" in body else "\n"
        flat = body.replace("\r\n", "\n")
        if pb["before"] not in flat:
            self.fail("%s/%s: anchor %r not found - the launcher changed under "
                      "us, so this recipe is stale"
                      % (title, pb["file"], pb["before"]))
            return
        flat = flat.replace(pb["before"],
                            "\n".join(pb["lines"]) + "\n\n" + pb["before"], 1)
        out = flat.replace("\n", nl) if nl == "\r\n" else flat
        if not self.dry:
            write(path, out)
        self.note("%s/%s [%s]" % (title, pb["file"], pb["marker"]))

    def new_launcher(self, tdir, title, name, spec):
        exe, mod = spec
        path = os.path.join(tdir, name)
        disp = name[len("Play "):-len(".bat")] if name.startswith("Play ") else name
        if exe.upper() == "GLQUAKE.EXE":
            block = "\n".join([call_cap(1280, 960)])
            text = NEW_GLQUAKE.format(block=block)
        elif title in ("SiNGold", "SoldierOfFortune"):
            block = "\n".join([CALL] + q2_cfg(mod))
            text = NEW_Q2.format(title=disp, exe=exe, block=block)
        else:
            block = "\n".join([CALL] + idtech3_cfg(mod))
            text = NEW_IDTECH3.format(title=disp, exe=exe, block=block,
                                      args=idtech3_args())
        self.put(path, crlf(text), "%s/%s" % (title, name))

    def strip_latched(self, tdir, title, rel):
        """Delete the CVAR_LATCH resolution seta lines from a staged
        autoexec.cfg and exec fleetres.cfg instead.

        These two lines are the whole reason the command line did not take on
        .123: they run after Com_StartupVariable and before R_Init, so the
        renderer comes up on THEIR value. Removing them and supplying the mode
        from the launcher is the actual fix — but only once the launcher does
        supply it, which is why both halves are in this one script."""
        path = os.path.join(tdir, rel.replace("/", os.sep))
        if not os.path.isfile(path):
            self.fail("%s/%s: missing" % (title, rel))
            return
        body = read(path)
        out, dropped = [], 0
        for line in body.replace("\r\n", "\n").split("\n"):
            if re.match(r'\s*seta\s+r_(mode|fullscreen)\s', line):
                dropped += 1
                continue
            # the trailing comment lines that belonged to the r_mode line
            if dropped and re.match(r'\s{8,}//', line):
                continue
            out.append(line)
        text = "\n".join(out)
        text = self._append_exec(text)
        if dropped == 0 and "exec fleetres.cfg" in body:
            self.skipped += 1
            return
        if dropped == 0:
            self.fail("%s/%s: no 'seta r_mode'/'seta r_fullscreen' to remove "
                      "— check the file, do not assume it is already done"
                      % (title, rel))
            return
        self.put(path, crlf(text), "%s/%s" % (title, rel))

    def add_exec(self, tdir, title, rel):
        path = os.path.join(tdir, rel.replace("/", os.sep))
        if not os.path.isfile(path):
            self.fail("%s/%s: missing" % (title, rel))
            return
        body = read(path).replace("\r\n", "\n")
        if "exec fleetres.cfg" in body:
            self.skipped += 1
            return
        self.put(path, crlf(self._append_exec(body)), "%s/%s" % (title, rel))

    @staticmethod
    def _append_exec(text):
        if "exec fleetres.cfg" in text:
            return text
        tail = (
            "\n"
            "// ---- per-box resolution ---------------------------------------\n"
            "// fleetres.cfg is written by this title's Play ....bat at every\n"
            "// launch, from the panel FLEETRES.EXE measures on THIS machine.\n"
            "// It is exec'd LAST so it beats anything set above, and it is not\n"
            "// shipped in the library - one staged tree serves eight different\n"
            "// monitors, so a resolution constant here is wrong somewhere by\n"
            "// construction. If the file is absent the engine prints a harmless\n"
            "// 'couldn't exec' and keeps its own defaults.\n"
            "exec fleetres.cfg\n")
        return text.rstrip("\n") + "\n" + tail

    def launch_txt(self, tdir, title, rows=None, line0=None):
        path = os.path.join(tdir, "launch.txt")
        body = read(path)
        nl = "\r\n" if "\r\n" in body else "\n"
        lines = body.replace("\r\n", "\n").split("\n")
        if rows is not None:
            data = ["\t".join(r) for r in rows]
            rest = [l for l in lines if l.strip().startswith("#") or not l.strip()]
            new = nl.join(data + rest)
        else:
            done = False
            for i, l in enumerate(lines):
                if l.strip() and not l.strip().startswith("#"):
                    lines[i] = "\t".join(line0)
                    done = True
                    break
            if not done:
                self.fail("%s/launch.txt: no data line to rewrite" % title)
                return
            new = nl.join(lines)
        self.put(path, new, "%s/launch.txt" % title)

    def run(self):
        for title in sorted(TITLES):
            spec = TITLES[title]
            tdir = os.path.join(self.lib, title)
            if not os.path.isdir(tdir):
                self.fail("%s: not in the library" % title)
                continue
            self.payload(tdir, title)
            for name, r in sorted(spec.get("launchers", {}).items()):
                self.patch_launcher(tdir, title, name, r)
            for name, s in sorted(spec.get("new", {}).items()):
                self.new_launcher(tdir, title, name, s)
            for rel in spec.get("cfg_strip", []):
                self.strip_latched(tdir, title, rel)
            for rel in spec.get("cfg_exec", []):
                self.add_exec(tdir, title, rel)
            for pb in spec.get("post", []):
                self.post_block(tdir, title, pb)
            for name, pairs in sorted(spec.get("fix", {}).items()):
                self.repair(tdir, title, name, pairs)
            if "launch_txt" in spec:
                self.launch_txt(tdir, title, rows=spec["launch_txt"])
            if "launch_txt_line0" in spec:
                self.launch_txt(tdir, title, line0=spec["launch_txt_line0"])
        return self


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--lib", default=LIB_DEFAULT)
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--check", action="store_true",
                    help="report what is NOT staged and exit 1; changes nothing")
    a = ap.parse_args()

    if not os.path.isdir(a.lib):
        print("library not mounted at %s" % a.lib, file=sys.stderr)
        return 2

    r = Runner(a.lib, a.dry_run, a.check).run()
    for c in r.changed:
        print("%s %s" % ("would stage" if a.dry_run else "staged", c))
    for e in r.errors:
        print("FAIL %s" % e, file=sys.stderr)
    print("\n%d staged, %d already current, %d failures"
          % (len(r.changed), r.skipped, len(r.errors)))
    return 1 if r.errors else 0


if __name__ == "__main__":
    sys.exit(main())
