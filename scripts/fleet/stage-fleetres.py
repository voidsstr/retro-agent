#: Markers that identify a launcher generated by the DISC-MOUNT generator
#: (provisioning/discmount/mount-launcher-template.bat + a spec). Detected by
#: CONTENT rather than by a filename list, so it also protects titles added
#: after this was written - a list here would go stale the first time a spec is
#: added, which is the same class of failure one level up.
#:
#: THIS COLLISION HAS ALREADY HAPPENED. new_launcher() writes a launcher from
#: scratch and put() overwrites whenever the content differs, so a run of this
#: tool replaced Jedi Academy's 22 KB generated mount launcher with a 2 KB one
#: carrying NO DISC MOUNT AT ALL - silently, on a title whose entire fix was the
#: mount, and with both tools reporting success. Two mechanisms claimed
#: `<title>/Play <name>.bat` and nothing said so.
DISCMOUNT_MARKERS = ('set "REQUIREDISC=', 'call :finddisc', ':waitdisc')


def is_discmount_launcher(path):
    """True if this .bat is one the disc-mount generator owns."""
    if not os.path.isfile(path):
        return False
    try:
        body = read(path)
    except Exception:
        return False
    return all(m in body for m in DISCMOUNT_MARKERS)


