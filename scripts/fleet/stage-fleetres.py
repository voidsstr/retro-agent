# --------------------------------------------------------------------------
# The per-box RENDER DEVICE block. Structurally the same problem as the
# resolution: one staged tree, eight boxes, and a game-local nGlide
# glide2x.dll that is RIGHT on the six boxes with no Glide silicon and WRONG
# on the two that have it, because game-local wins at load time and shadows
# the real system32 glide2x.dll. On .171 that cost a whole session: UnrealGold
# was reported as crashing, had never crashed, and had spent the time on the
# software rasterizer at 100% CPU because the wrapper's grSstOpen failed (2,3).
#
# The wrapper is NOT deleted - it is the only Glide path the other six boxes
# have. It is moved aside per box, at launch, and put back when the box has
# no 3dfx card. Both directions matter: a tree that only ever renames one way
# would strand the wrapper aside after the card came out.
#
# Since 2026-10-01 the LIBRARY ships the wrapper as <dll>.nglide (see "GAME-
# LOCAL WRAPPERS SHIP UNDER INERT NAMES"), so the way back is a COPY: the
# library's .nglide stays where GAMESYNC put it and is never recopied. A move
# would take it away at every first launch and cost a recopy at the next sync.
# --------------------------------------------------------------------------
def glide_swap(*rels):
    """rels = the game-local wrapper files, relative to the title root.

    EVERY Glide DLL of the wrapper, not only the one the game imports: on a
    box with real silicon the game falls through to system32's glide2x.dll,
    which on a Voodoo 4/5 is the Glide2-to-Glide3 translator - and it loads
    glide3x.dll BY NAME, application directory first. Carmageddon2 ships
    nGlide's glide3x.dll (and glide.dll) beside glide2x.dll, so moving only
    glide2x aside handed the translator nGlide's glide3x, and BRender stopped
    with "Unable to allocate Main Front Screen" (.124, V5 6000, 2026-09-28)."""
    ws = ['%~dp0' + rel for rel in rels]
    out = ['rem ---- per-box RENDER DEVICE (see stage-fleetres.py) --------------',
           'if "%FR_GLIDE%"=="1" (']
    out += ['  if exist "%s" move /y "%s" "%s.nglide" >nul' % (w, w, w) for w in ws]
    out.append(') else (')
    out += ['  if not exist "%s" if exist "%s.nglide" copy /y "%s.nglide" "%s" >nul'
            % (w, w, w, w) for w in ws]
    out.append(')')
    return out


