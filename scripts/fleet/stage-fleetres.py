FLEETRES_BAT = """\
@echo off
rem ==========================================================================
rem  FLEET RESOLUTION BLOCK - identical in every staged title.
rem  Generated by retro-agent scripts/fleet/stage-fleetres.py. Do not hand-edit
rem  a copy: fix the generator and re-stage, or the next title you touch will
rem  disagree with this one.
rem
rem  ONE staged tree deploys to EIGHT monitors, so a resolution written into a
rem  staged config is wrong somewhere BY CONSTRUCTION. FLEETRES.EXE reads THIS
rem  box's panel - the EDID native mode plus the driver's own mode list - and
rem  answers with the FR_* variables below.
rem
rem  It deliberately does NOT trust two things that look authoritative:
rem    * wmic Win32_VideoController.CurrentHorizontalResolution, which reported
rem      640x480 on .123 while the box was really at 1024x768;
rem    * the LIVE desktop mode, because a game that exits without restoring
rem      leaves the desktop at 640x480 (.123 and .240 were both sitting there
rem      mid-survey) and a launcher trusting it would pin every later game to
rem      640x480 for good. The PERSISTED mode is what it reads.
rem
rem  Usage:  call "%~dp0FLEETRES.BAT"            (whole panel)
rem          call "%~dp0FLEETRES.BAT" -cap 1024 768   (engine ceiling)
rem
rem  FR_W    / FR_H    resolution for an engine that can do widescreen
rem  FR_W43  / FR_H43  resolution for an engine that is 4:3-only
rem  FR_Q2MODE         id Tech 2 gl_mode index matching FR_W43/FR_H43
rem  FR_Q3MODE         id Tech 3 r_mode index - a DIFFERENT TABLE: id Tech 2's
rem                    mode 8 is 1280x960 (4:3), id Tech 3's is 1280x1024 (5:4),
rem                    so handing FR_Q2MODE to a Quake III-family engine asks a
rem                    16:9 panel for a squashed picture
rem  FR_FOV            hor+ FOV preserving the 4:3 vertical FOV (90 at 4:3)
rem  FR_DOSFULLRES     DOSBox [sdl] fullresolution: desktop on an LCD,
rem                    original on a CRT
rem  FR_GLIDE          1 when this box has REAL 3dfx silicon (VEN_121A in the
rem                    PCI enum - a Voodoo 2 is Class=MEDIA and never shows up
rem                    as a display adapter, so nothing else can see it). The
rem                    launcher moves the game-local nGlide glide2x.dll aside
rem                    when this is 1, because game-local shadows system32 and
rem                    the wrapper then blocks the card it is standing in for.
rem  FR_UE1DEV         the UE1 render device to write into the game's .ini
rem ==========================================================================
set FR_W=
set FR_H=
set FR_W43=
set FR_H43=
set FR_FOV=
set FR_Q2MODE=
set FR_DOSFULLRES=
set FR_PANEL=
set FR_Q3MODE=
set FR_GLIDE=
set FR_UE1DEV=
if not defined TEMP set TEMP=%SystemRoot%\\Temp
if exist "%~dp0FLEETRES.EXE" "%~dp0FLEETRES.EXE" -cmd %1 %2 %3 > "%TEMP%\\fleetres.cmd"
if exist "%TEMP%\\fleetres.cmd" call "%TEMP%\\fleetres.cmd"
rem Fallbacks, for a box where FLEETRES.EXE is missing or the panel is unreadable.
rem 1024x768 is the fleet's lowest common denominator, not a preference.
if not defined FR_W set FR_W=1024
if not defined FR_H set FR_H=768
if not defined FR_W43 set FR_W43=1024
if not defined FR_H43 set FR_H43=768
if not defined FR_FOV set FR_FOV=90
if not defined FR_Q2MODE set FR_Q2MODE=6
if not defined FR_Q3MODE set FR_Q3MODE=6
if not defined FR_DOSFULLRES set FR_DOSFULLRES=original
rem FR_GLIDE defaults to 0 - "no 3dfx silicon" - deliberately. The wrong way
rem round would move the nGlide wrapper aside on a box that has nothing else,
rem costing six machines a working renderer to help two.
if not defined FR_GLIDE set FR_GLIDE=0
if not defined FR_UE1DEV set FR_UE1DEV=D3DDrv.D3DRenderDevice
"""


def idtech3_cfg(mod, wide=True):
    """The cfg the staged autoexec.cfg execs, written fresh at every launch.

    r_mode / r_customwidth / r_customheight / r_fullscreen are CVAR_LATCH: they
    bite only at renderer init. The staged autoexec.cfg used to `seta r_mode 6`
    there, which beat the command line on .123. That seta is now gone from the
    library and `exec fleetres.cfg` is the LAST line of autoexec.cfg instead, so
    whatever the box's own config wrote earlier is overridden in the same pass.
    """
    w, h = ("%FR_W%", "%FR_H%") if wide else ("%FR_W43%", "%FR_H43%")
    p = '"%%~dp0%s\\fleetres.cfg"' % mod
    lines = [
        '> %s echo // written by the launcher at every start - do not edit' % p,
        '>>%s echo seta r_mode "-1"' % p,
        '>>%s echo seta r_customwidth "%s"' % (p, w),
        '>>%s echo seta r_customheight "%s"' % (p, h),
        '>>%s echo seta r_customaspect "1"' % p,
        '>>%s echo seta r_customPixelAspect "1"' % p,
        '>>%s echo seta r_fullscreen "1"' % p,
    ]
    if wide:
        # id Tech 3 is vert-: at 16:9 with the default FOV you see LESS
        # vertically, not more horizontally. FR_FOV restores the 4:3 vertical
        # field of view (106 at 16:9, 90 at 4:3).
        lines.append('>>%s echo seta cg_fov "%%FR_FOV%%"' % p)
    return lines


def idtech3_modecfg(mod):
    """For an id Tech 3 fork with NO r_mode -1 BRANCH.

    `r_mode -1` + r_customwidth/r_customheight is the standard idiom and it is
    NOT universal: measured on .145 with an identical fleetres.cfg,
    quake3.exe/jasp.exe/jamp.exe all came up at 1920x1080 and **sof2mp.exe came
    up at 640x480**. It does not error - it renders small - which is exactly
    the silent class of defect this repo keeps paying for.

    So this fork gets a plain mode INDEX, and it must be FR_Q3MODE and not
    FR_Q2MODE: the two engines' tables differ at index 8, which is 1280x960
    (4:3) in id Tech 2 and 1280x1024 (5:4) in id Tech 3. Asking a 16:9 panel
    for 1280x1024 is the squashed picture this whole mechanism removes."""
    p = '"%%~dp0%s\\fleetres.cfg"' % mod
    return [
        '> %s echo // written by the launcher at every start - do not edit' % p,
        '>>%s echo // r_mode -1 DOES NOT EXIST IN THIS ENGINE - a plain index,' % p,
        '>>%s echo // and FR_Q3MODE not FR_Q2MODE: idTech3 mode 8 is 1280x1024.' % p,
        '>>%s echo seta r_mode "%%FR_Q3MODE%%"' % p,
        '>>%s echo seta r_fullscreen "1"' % p,
        '>>%s echo seta cg_fov "%%FR_FOV%%"' % p,
    ]


def idtech3_modeargs():
    return ('+set r_mode %FR_Q3MODE% +set r_fullscreen 1 +set cg_fov %FR_FOV%')


def idtech3_args(wide=True, fov=True):
    w, h = ("%FR_W%", "%FR_H%") if wide else ("%FR_W43%", "%FR_H43%")
    a = ("+set r_mode -1 +set r_customwidth {w} +set r_customheight {h} "
         "+set r_customaspect 1 +set r_customPixelAspect 1 "
         "+set r_fullscreen 1").format(w=w, h=h)
    if fov:
        a += " +set cg_fov %FR_FOV%"
    return a


def q2_cfg(mod):
    """id Tech 2 has a FIXED mode table indexed by gl_mode and no custom mode:
    0=320x240 ... 6=1024x768 ... 9=1600x1200, no 16:9 entry anywhere. So the
    honest best on a 16:9 panel is a correctly proportioned 4:3 mode, which is
    what FR_Q2MODE indexes."""
    p = '"%%~dp0%s\\fleetres.cfg"' % mod
    return [
        '> %s echo // written by the launcher at every start - do not edit' % p,
        '>>%s echo set gl_mode "%%FR_Q2MODE%%"' % p,
        '>>%s echo set vid_fullscreen "1"' % p,
    ]


def ue_ini(ini, section="WinDrv.WindowsClient"):
    """Unreal Engine 1/2 keeps the fullscreen mode in its .ini, and the engine
    rewrites that file on exit, so it has to be written before every launch."""
    e = '"%~dp0FLEETRES.EXE"'
    i = '"%%~dp0%s"' % ini
    return [
        'if exist "%~dp0FLEETRES.EXE" (',
        '  %s -ini %s %s FullscreenViewportX %%FR_W%%' % (e, i, section),
        '  %s -ini %s %s FullscreenViewportY %%FR_H%%' % (e, i, section),
        '  %s -ini %s %s StartupFullscreen True' % (e, i, section),
        ')',
    ]


def dosbox_conf(conf):
    """fullresolution=original changes the WHOLE DESKTOP to the DOS mode - on a
    16:9 LCD that is a stretched 640x480 upscale, and it is left behind after a
    crash (measured on .145 with DISPLAYCFG). =desktop keeps the desktop mode
    and lets DOSBox pillarbox correctly with aspect=true. On a CRT `original` is
    still right, which is why this is per-box and not a staged constant."""
    return ['if exist "%%~dp0FLEETRES.EXE" "%%~dp0FLEETRES.EXE" -ini '
            '"%%~dp0%s" sdl fullresolution %%FR_DOSFULLRES%%' % conf]


def kv_cfg(conf, pairs):
    """DXX-Rebirth writes DESCENT.CFG as bare `ResolutionX=1024` with NO
    [section] header, so WritePrivateProfileString cannot address it and
    -setline cannot match it (the whole "ResolutionX=1024" is one whitespace
    token). -kv splits at the '=' instead."""
    e = '"%~dp0FLEETRES.EXE"'
    out = ['if exist "%~dp0FLEETRES.EXE" (']
    for k, v in pairs:
        out.append('  %s -kv "%%~dp0%s" %s %s' % (e, conf, k, v))
    out.append(')')
    return out


def reg_cfg(root, subkey, values):
    r"""Some engines keep the mode ONLY in the registry - Max Payne through
    MFC's SetRegistryKey("Remedy Entertainment"), Red Faction under
    HKLM\SOFTWARE\Volition. Nothing that ships in the tree can set those, so
    a box inherits whatever stale hive it happens to have. FLEETRES -reg is
    used rather than reg.exe because reg.exe does not exist on Win9x."""
    e = '"%~dp0FLEETRES.EXE"'
    out = ['if exist "%~dp0FLEETRES.EXE" (']
    for name, typ, data in values:
        out.append('  %s -reg %s "%s" "%s" %s %s' % (e, root, subkey, name, typ, data))
    out.append(')')
    return out


def setline_cfg(conf, entries):
    e = '"%~dp0FLEETRES.EXE"'
    out = ['if exist "%~dp0FLEETRES.EXE" (']
    for key, line in entries:
        out.append('  %s -setline "%%~dp0%s" %s %s' % (e, conf, key, line))
    out.append(')')
    return out


# --------------------------------------------------------------------------
# The per-box RENDER DEVICE block. Structurally the same problem as the
# resolution: one staged tree, eight boxes, and a game-local nGlide
# glide2x.dll that is RIGHT on the six boxes with no Glide silicon and WRONG
# on the two that have it, because game-local wins at load time and shadows
# the real system32 glide2x.dll. On .171 that cost a whole session: UnrealGold
# was reported as crashing, had never crashed, and had spent the time on the
# software rasterizer at 100% CPU because the wrapper's grSstOpen failed (2,3).
#
# The wrapper is NOT deleted - it is the only Glide path the other six boxes
# have. It is moved aside per box, at launch, and moved back when the box has
# no 3dfx card. Both directions matter: a tree that only ever renames one way
# would strand the wrapper aside after the card came out.
# --------------------------------------------------------------------------
def glide_swap(rel):
    """rel = the game-local wrapper's path relative to the title root."""
    w = '%~dp0' + rel
    return [
        'rem ---- per-box RENDER DEVICE (see stage-fleetres.py) --------------',
        'if "%FR_GLIDE%"=="1" (',
        '  if exist "%s" move /y "%s" "%s.nglide" >nul' % (w, w, w),
        ') else (',
        '  if not exist "%s" if exist "%s.nglide" move /y "%s.nglide" "%s" >nul'
        % (w, w, w, w),
        ')',
    ]


# --------------------------------------------------------------------------
# Turok 2 keeps its mode as one BOOLEAN PER MODE in Data\config.ned, chosen
# from a fixed list: 320x240, 512x384, 640x480, 800x600, 1024x768, 1280x1024.
# There is no width/height pair and no 1080p entry, so the honest best is the
# largest 4:3 mode on that list the box can drive. 1280x1024 is deliberately
# NOT on the ladder: it is 5:4, and putting a 5:4 mode on a 4:3 or 16:9 panel
# squashes the picture - which is the same fault this whole mechanism exists
# to fix on .133 and .171.
#
# The `^` in the key is literal INSIDE double quotes; unquoted, cmd.exe eats it
# as its own escape character and the key silently becomes "320x240".
# --------------------------------------------------------------------------
T2_MODES = ["320^x^240", "512^x^384", "640^x^480", "800^x^600",
            "1024^x^768", "1280^x^1024"]
T2_LADDER = [(640, "640^x^480"), (800, "800^x^600"), (1024, "1024^x^768")]


def turok2_mode():
    e = '"%~dp0FLEETRES.EXE"'
    f = '"%~dp0Data\\config.ned"'
    k = 'Acclaim\\Turok\\VideoD3D\\'
    out = ['set T2SEL=640^x^480']
    for w, m in T2_LADDER[1:]:
        out.append('if %%FR_W43%% GEQ %d set T2SEL=%s' % (w, m))
    out.append('if exist "%~dp0FLEETRES.EXE" (')
    for m in T2_MODES:
        out.append('  %s -setline %s "%s%s" "%s%s" 0' % (e, f, k, m, k, m))
    out.append('  %s -setline %s "%s%%T2SEL%%" "%s%%T2SEL%%" 1' % (e, f, k, k))
    out.append('  %s -setline %s "%sWindowed" "%sWindowed" 0' % (e, f, k, k))
    out.append(')')
    return out


CALL = 'call "%~dp0FLEETRES.BAT"'
def call_cap(w, h):
    return 'call "%~dp0FLEETRES.BAT" -cap ' + str(w) + ' ' + str(h)


# --------------------------------------------------------------------------
# Per-title recipes.
#
#   before : a line that must exist in the .bat; the block is inserted above it
#   pre    : lines of the block
#   sub    : (regex, replacement) applied once to the launch line, and it MUST
#            match - an unmatched substitution aborts the whole run
# --------------------------------------------------------------------------
def rec(before, pre, sub=None):
    return {"before": before, "pre": pre, "sub": sub}


def q3(mod, exe, extra=""):
    args = idtech3_args()
    old = re.escape('start "" %s%s' % (exe, extra))
    return rec('cd /d "%~dp0"',
               [CALL] + idtech3_cfg(mod),
               (old, 'start "" %s%s %s' % (exe, extra, args)))


