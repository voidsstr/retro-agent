#!/usr/bin/env python3
"""The Windows 9x lane of library titles that ALSO serve the NT fleet.

WHY THIS EXISTS. A staged title deploys to every box, and on Windows 98 SE
(.243 - a Pentium 166 with a Voodoo 2, a Cirrus GD5436 and an SB16; and the
W98BUILD VM shaped like it) the title's NT launchers cannot run: they are
cmd.exe dialect (%~dp0, cd /d, start "", if-blocks) and COMMAND.COM starts
none of them. Those boxes need launchers of their own - a Voodoo launcher that
renders through the 3dfx MiniGL or Glide, a DOS launcher that runs the game's
own DOS build in a DOS box - with requires.json rules that put each launcher
on the right boxes and keep the NT ones off Win9x.

Until now those launchers were hand-written on the share, with nothing in the
repo that could regenerate one, check one, or say what it should contain. This
generator owns them, the same way stage-fleetres.py owns the FLEETRES blocks:

  * each launcher's whole text (COMMAND.COM dialect, checked by
    libmeta.command_com_problems() before anything is written - a launcher that
    fails it stops the run, it is never shipped);
  * the binary payloads a launcher needs (md5-pinned, scripts/fleet/libsource.py),
    the small text files it reads (HLV9X.REG), and files DERIVED from another
    library file (Unreal Gold's System\\Voodoo.tpl, made from its Unreal.ini
    and remade whenever that changes);
  * its launch.txt rows and requires.json rules - MERGED, never templated
    (scripts/fleet/libmeta.py): other generators and people own the rest;
  * the removal of a file it shipped and then replaced - LAST, and only while
    the file holds exactly the bytes it shipped (md5-pinned).

Titles: Quake1 and Descent2 (DOS builds and the Quake MiniGL), and the Win9x
3dfx Voodoo launchers of SiNGold, HalfLife1, Quake2Complete, UnrealGold and
Carmageddon2. The game-local Glide/IPX wrappers those last two shipped LIVE
are renamed inert by stage-fleetres.py ("GAME-LOCAL WRAPPERS SHIP UNDER INERT
NAMES"), which owns their NT launchers.

    python3 scripts/fleet/stage-win9x.py                 # apply
    python3 scripts/fleet/stage-win9x.py --check         # exit 1 if the share differs
    python3 scripts/fleet/stage-win9x.py --dry-run       # say what would change
    python3 scripts/fleet/stage-win9x.py --only Quake1   # one title

Writes go through scripts/fleet/libwrite.py: one file at a time, read back
through /mnt (md5 + a fresh write time) before the next, the first failure
stops the run. Identical bytes are never rewritten. It never creates a title,
never deletes a launcher (GAMESYNC never deletes either - a box keeps an old
launcher until someone removes it, so a superseded one is left for a person to
delete once its replacement is verified on hardware), and writes launch.txt
LAST so no box can sync a row that names a launcher not yet on the share.
"""
