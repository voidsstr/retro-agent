# Payload first, launchers next, rules after them, launch.txt LAST.
ORDER = ("copies", "files", "bats", "requires", "launch")


class Runner:
    def __init__(self, lib, check=False, dry=False, writer=None, via_smb=False,
                 log=print, titles=None):
        self.lib, self.check, self.dry = lib, check, dry
        self.log = log
        self.titles = titles if titles is not None else TITLES
        self.writer = writer or libwrite.writer_for(lib, via_smb=via_smb)
        self.changed, self.current, self.problems = [], 0, []

    # ---- reading the share ------------------------------------------------
    def _path(self, tdir, rel):
        """The existing file for `rel` (any case), else where to create it."""
        hit = libsource.find_ci_path(tdir, rel)
        if hit:
            return hit
        parent = os.path.dirname(rel.replace("\\", "/"))
        pdir = libsource.find_ci_path(tdir, parent) if parent else tdir
        if parent and pdir is None:
            pdir = os.path.join(tdir, *parent.split("/"))
        return os.path.join(pdir, os.path.basename(rel.replace("\\", "/")))

    @staticmethod
    def _read(path):
        try:
            with open(path, "rb") as fh:
                return fh.read()
        except FileNotFoundError:
            return None

    # ---- what the title should hold ----------------------------------------
    def desired(self, title, spec, tdir):
        """[(kind, rel, bytes)] in write order. Raises on a launcher that fails
        the COMMAND.COM check or a launch.txt that would lose a shortcut."""
        out = []
        for rel, src in sorted(spec.get("copies", {}).items()):
            out.append(("copies", rel, libsource.fetch(src)))
        for rel, text in sorted(spec.get("files", {}).items()):
            out.append(("files", rel, crlf(text).encode("latin-1")))
        # a file computed from another library file (Unreal Gold's Voodoo.ini
        # from its Unreal.ini): regenerated whenever its source changes
        for rel, (src_rel, fn) in sorted(spec.get("derive", {}).items()):
            src = libsource.find_ci_path(tdir, src_rel)
            if src is None:
                raise SystemExit("%s: %s is missing - cannot derive %s"
                                 % (title, src_rel, rel))
            with open(src, "rb") as fh:
                text = fh.read().decode("latin-1")
            out.append(("files", rel, fn(text).encode("latin-1")))
        for rel, text in sorted(spec.get("bats", {}).items()):
            data = crlf(text).encode("ascii")
            probs = libmeta.command_com_problems(data)
            if probs:
                raise SystemExit("%s/%s fails the COMMAND.COM check - refusing to "
                                 "ship it: %s" % (title, rel, "; ".join(probs)))
            out.append(("bats", rel, data))
        req = spec.get("requires")
        if req:
            cur = self._read(self._path(tdir, "requires.json"))
            text = libmeta.merge_requires(
                (cur or b"").decode("utf-8"), version=req.get("version"),
                set_shortcuts=req.get("set"), patch_shortcuts=req.get("patch"),
                drop_shortcuts=req.get("drop", ()), set_top=req.get("set_top"),
                drop_top=req.get("drop_top", ()), notes_add=req.get("notes"))
            out.append(("requires", "requires.json", text.encode("utf-8")))
        lt = spec.get("launch")
        if lt:
            cur = self._read(self._path(tdir, "launch.txt"))
            text = libmeta.set_launch_rows((cur or b"").decode("latin-1"),
                                           lt.get("rows", ()), lt.get("drop", ()),
                                           lt.get("note"))
            probs = libmeta.launch_problems(text)
            if probs:
                raise SystemExit("%s/launch.txt would lose a shortcut: %s"
                                 % (title, "; ".join(probs)))
            out.append(("launch", "launch.txt", text.encode("latin-1")))
        rank = {k: i for i, k in enumerate(ORDER)}
        out.sort(key=lambda t: rank[t[0]])
        return out

    def run(self):
        for title in sorted(self.titles):
            spec = self.titles[title]
            tdir = libsource.find_ci_path(self.lib, title)
            if tdir is None:
                # never create a title: retro-autodeploy answers a new title
                # directory with a fleet-wide GAMESYNC RESET + START
                self.problems.append("%s: not in the library" % title)
                continue
            for kind, rel, data in self.desired(title, spec, tdir):
                path = self._path(tdir, rel)
                if self._read(path) == data:
                    self.current += 1
                    continue
                what = "%s/%s" % (title, rel)
                if self.check:
                    self.problems.append("%s: not current" % what)
                    continue
                if not self.dry:
                    self.writer.write_bytes(path, data)
                self.changed.append(what)
            # LAST, after everything that replaces the file is in place. Only
            # the exact bytes this generator once shipped are ever removed.
            for rel, md5 in sorted(spec.get("remove", {}).items()):
                path = libsource.find_ci_path(tdir, rel)
                if path is None:
                    self.current += 1
                    continue
                what = "%s/%s" % (title, rel)
                have = libsource.md5(self._read(path))
                if have != md5:
                    self.problems.append("%s: not the file this generator shipped "
                                         "(md5 %s) - left alone" % (what, have))
                    continue
                if self.check:
                    self.problems.append("%s: should be removed" % what)
                    continue
                if not self.dry:
                    self.writer.remove(path)
                self.changed.append(what + " [removed]")
        return self


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--lib", default=LIB_DEFAULT)
    ap.add_argument("--only", action="append", default=[], metavar="TITLE")
    ap.add_argument("--check", action="store_true",
                    help="exit 1 if the share is not what this generator makes; writes nothing")
    ap.add_argument("--dry-run", action="store_true")
    libwrite.add_arguments(ap)
    a = ap.parse_args(argv)
    if not os.path.isdir(a.lib):
        print("library not mounted at %s" % a.lib, file=sys.stderr)
        return 2
    titles = TITLES
    if a.only:
        unknown = sorted(set(a.only) - set(TITLES))
        if unknown:
            print("--only names titles this generator does not own: %s" % unknown,
                  file=sys.stderr)
            return 2
        titles = {t: TITLES[t] for t in a.only}
    try:
        r = Runner(a.lib, a.check, a.dry_run, via_smb=a.via_smb, titles=titles)
    except libwrite.LibWriteError as e:
        print(str(e), file=sys.stderr)
        return 2
    try:
        with r.writer:
            r.run()
    except (libwrite.LibWriteError, libsource.SourceError) as e:
        for c in r.changed:
            print("staged %s" % c)
        print(libwrite.failure_banner(e, r.writer), file=sys.stderr)
        return 3
    for c in r.changed:
        print("%s %s" % ("would stage" if a.dry_run else "staged", c))
    for p in r.problems:
        print("FAIL %s" % p, file=sys.stderr)
    print("\n%d staged, %d already current, %d problem(s)"
          % (len(r.changed), r.current, len(r.problems)))
    return 1 if r.problems else 0


if __name__ == "__main__":
    sys.exit(main())
