        "rem Agents older than 1.84.0 ignore the glide rule in requires.json, so this",
        "rem launcher checks for Glide itself rather than failing in the game.",
        "if not exist %s goto notree" % check,
        "if exist %windir%\\SYSTEM32\\GLIDE2X.DLL goto glide",
        "if exist %windir%\\SYSTEM\\GLIDE2X.DLL goto glide",
