def q1pack_bats():
    out = {}
    for switch, folder, name, vbat, dbat in Q1_PACKS:
        out[vbat] = q1pack_voodoo(switch, folder, name)
        out[dbat] = q1pack_dos(switch, folder, name)
    return out


def q1pack_rows():
    rows = []
    for switch, folder, name, vbat, dbat in Q1_PACKS:
        icon9x = "QROGUE.ICO" if switch == "rogue" else "VOODOO\\GLQUAKE.EXE"
        icon_nt = "QROGUE.ICO" if switch == "rogue" else "GLQUAKE.EXE"
        rows += [("Play Quake - %s.bat" % name, "Quake - %s" % name, icon_nt),
                 (vbat, "Quake - %s - 3dfx Voodoo" % name, icon9x),
                 (dbat, "Quake - %s - DOS" % name, icon9x)]
    return rows


def q1pack_rules():
    rules = {}
    for switch, folder, name, vbat, dbat in Q1_PACKS:
        # the NT launcher is stage-fleetres.py's GLQuake template with -<pack>:
        # the same rule as Play Quake.bat
        rules["Play Quake - %s.bat" % name] = {"gpu_feature_level": "fixed",
                                               "min_vram_mb": 4, "min_os": "win2k"}
        rules[vbat] = {"requires_capabilities": ["glide"], "max_os": "win9x"}
        rules[dbat] = {"max_os": "win9x"}
    return rules


