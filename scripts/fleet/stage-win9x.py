def ini_set(text, edits):
    """`text` (an .ini) with each (section, key, value) set - replaced in place,
    or added at the end of its section when missing. Every other byte is kept;
    the line ending is the file's own."""
    nl = "\r\n" if "\r\n" in text else "\n"
    lines = text.replace("\r\n", "\n").split("\n")
    want = {}
    for sec, key, val in edits:
        want.setdefault(sec.lower(), {})[key.lower()] = (key, val)
    done = set()
    out, sec = [], None

    def flush(section):
        add = [(k, v) for kl, (k, v) in want.get(section, {}).items()
               if (section, kl) not in done]
        at = len(out)
        while at > 0 and not out[at - 1].strip():
            at -= 1
        out[at:at] = ["%s=%s" % (k, v) for k, v in add]
        done.update((section, k.lower()) for k, _ in add)

    for line in lines:
        st = line.strip()
        if st.startswith("[") and st.endswith("]"):
            if sec is not None:
                flush(sec)
            sec = st[1:-1].lower()
        elif sec in want and "=" in line and not st.startswith(";"):
            k = line.split("=", 1)[0].strip()
            if k.lower() in want[sec]:
                line = "%s=%s" % (k, want[sec][k.lower()][1])
                done.add((sec, k.lower()))
        out.append(line)
    if sec is not None:
        flush(sec)
    missing = [s for s in want if not any(d[0] == s for d in done)]
    if missing:
        raise SystemExit("ini_set: sections not in the ini: %s" % missing)
    return nl.join(out)


