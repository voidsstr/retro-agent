def q1dos(mode=None):
    run = "QUAKE.EXE -nojoy -nocdaudio -winmem 16"
    head = [
        "@echo off",
        "rem Quake - the DOS build, QUAKE.EXE 1.08, software rendering, in a Windows 9x",
        "rem DOS box. Generated by retro-agent scripts/fleet/stage-win9x.py - fix it there.",
        "rem COMMAND.COM dialect. The desktop shortcut starts in this folder and the",
        "rem DOS box goes full screen when Quake sets its video mode.",
    ]
    if mode is None:
        head += [
            "rem No mode is forced: mode 0, 320x200, or the one saved with D under",
            "rem Options, Video Options - which lists every mode this card offers. On",
            "rem .243 that is modes 0-10, VGA and Mode X up to 360x480: its Cirrus BIOS",
            "rem is VBE 1.2 and Quake's VESA modes need VBE 2.0.",
        ]
    else:
        run += " +vid_mode %d" % mode
        head += [
            "rem Mode %d = 360x480, the sharpest of the built-in VGA and Mode X modes," % mode,
            "rem about 2.7 times the pixels of 320x200. Quake's modes 0-10 are the same",
            "rem on every VGA card, and .243's Cirrus offers Quake no VESA mode at all.",
        ]
    head += [
        "rem -nojoy: with a gameport stick fitted Quake stops at CENTER the joystick.",
        "rem -nocdaudio: with no MSCDEX Quake stops at MSCDEX not loaded, press a key.",
        "rem -winmem 16: in a DOS box Quake takes an 8 MB heap unless it is told.",
        "rem Why DOS and not WinQuake: WINQUAKE.EXE stopped at MGL Fatal Error on",
        "rem .243's Cirrus 5436 with every -nowindirect and -nodirectdraw combination.",
        "if not exist QUAKE.EXE goto notree",
        run,
        "rem CLS: Windows 9x closes a DOS box on exit only when its screen is empty,",
        "rem and Quake prints its end text on the way out - measured on .243.",
        "cls",
        "goto end",
        ":notree",
        "echo QUAKE.EXE is missing - the Quake tree is incomplete.",
        "pause",
        ":end",
    ]
    return "\n".join(head) + "\n"


