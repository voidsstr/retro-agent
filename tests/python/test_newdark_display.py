#!/usr/bin/env python3
"""Thief II (NewDark 1.26) on vcr-kmd: the per-box DISPLAY SYSTEM block.

WHY THIS EXISTS. On .124 (Voodoo 5 6000, our vcr-kmd driver) the staged Thief
II refused to start - "Your video hardware is not supported or no supported
video mode was found" - with vcr-kmd's 32 bpp Direct3D OFF and ON (V5 plan
step 16). Static analysis of the staged Thief2.exe
(voodoo-cleanroom/vcr-kmd/evidence/newdark_thief2/) found why: NewDark's
Direct3D 9 display (`use_d3d_display`, which the staged cam_ext.cfg enables)
renders 32 bpp only and, at EVERY mode set, puts its 2D layer in one texture
the size of the screen rounded up to a power of two - X8R8G8B8/A8R8G8B8,
1024x512 at 640x480, 2048x1024 at 1280x1024. vcr-kmd's DX7-level HAL offers
16-bit textures of at most 256x256, so that CreateTexture fails, StartMode
returns 0 and the screen loop raises the dialog. No cam_ext.cfg option lowers
it.

The fix is in the LIBRARY, per box, like the nGlide swap: where the vcr-kmd
miniport is the running display driver, the launcher moves cam_ext.cfg aside
and NewDark runs its legacy DirectX 6 display at 16 bpp, whose device
validation asks only for what that HAL reports (in-game on vcr-kmd is still to
be seen on the box). Everywhere else nothing changes.

The block is generated by scripts/fleet/stage-fleetres.py (newdark_display_swap)
and these tests pin its LOGIC by executing it in a tiny model of the few
cmd.exe constructs it uses, over every state a box can be in. A construct the
model does not know fails the test instead of being skipped, so the block
cannot grow a line nobody has reasoned about.
"""
import hashlib
import importlib.util
import os
import re
import sys

import pytest

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.normpath(os.path.join(HERE, '..', '..'))
STAGER = os.path.join(REPO, 'scripts', 'fleet', 'stage-fleetres.py')
LIB = os.environ.get('RETRO_LIBRARY', '/mnt/retro-share/Files/Games-Library')
THIEF2 = os.path.join(LIB, 'Thief2')
ANALYSED_MD5 = '1109955d4d0a7855592b33d954abcb76'   # the Thief2.exe the analysis read


def _load(name, path):
    spec = importlib.util.spec_from_file_location(name, path)
    mod = importlib.util.module_from_spec(spec)
    sys.modules[name] = mod
    spec.loader.exec_module(mod)
    return mod


sf = _load('stage_fleetres_nd', STAGER)


def _block():
    pbs = sf.TITLES['Thief2'].get('post', [])
    nd = [pb for pb in pbs if pb.get('marker') == 'ND_DX6']
    assert len(nd) == 1, ('Thief2 has no ND_DX6 display block: on a vcr-kmd box '
                          'NewDark then opens its Direct3D 9 display and refuses '
                          '"Your video hardware is not supported"')
    return nd[0]


# ---------------------------------------------------------------------------
# a model of exactly the cmd.exe constructs the block uses
# ---------------------------------------------------------------------------
class Box:
    def __init__(self, running, files, have_sc=True):
        self.running = set(running)     # services sc.exe reports RUNNING
        self.files = set(files)         # names in the game directory
        self.have_sc = have_sc
        self.env = {}

    def expand(self, s):
        s = s.replace('%~dp0', '')
        return re.sub(r'%([A-Za-z_][A-Za-z0-9_]*)%',
                      lambda m: self.env.get(m.group(1), ''), s)

    def stmt(self, s):
        s = s.strip()
        m = re.fullmatch(r'if (not )?exist "([^"]+)" (.+)', s)
        if m:
            there = self.expand(m.group(2)) in self.files
            if there != bool(m.group(1)):
                self.stmt(m.group(3))
            return
        m = re.fullmatch(r'move /y "([^"]+)" "([^"]+)" >nul', s)
        if m:
            src, dst = self.expand(m.group(1)), self.expand(m.group(2))
            if src in self.files:        # move /y replaces an existing dst
                self.files.discard(src)
                self.files.add(dst)
            return
        m = re.fullmatch(r'set ([A-Za-z_][A-Za-z0-9_]*)=(\S*)', s)
        if m:
            self.env[m.group(1)] = self.expand(m.group(2))
            return
        m = re.fullmatch(r'if "([^"]*)"=="([^"]*)" (.+)', s)
        if m:                            # the single-line form (no block)
            if self.expand(m.group(1)) == m.group(2):
                self.stmt(m.group(3))
            return
        m = re.fullmatch(r'del /q "([^"]+)" >nul 2>&1', s)
        if m:
            self.files.discard(self.expand(m.group(1)))
            return
        m = re.fullmatch(r'echo [^>]+> "([^"]+)"', s)
        if m:
            self.files.add(self.expand(m.group(1)))
            return
        m = re.fullmatch(r'sc query (\S+) 2>nul \| find /i "RUNNING" >nul && (.+)', s)
        if m:
            if self.have_sc and m.group(1) in self.running:
                self.stmt(m.group(2))
            return
        raise AssertionError('the model does not know this line - reason about '
                             'it and teach the model: %r' % s)

    def run(self, lines):
        stack = []                       # one bool per open ( block: executing?
        for raw in lines:
            s = raw.strip()
            live = all(stack)
            if not s or s.lower().startswith('rem '):
                continue
            m = re.fullmatch(r'if "([^"]*)"=="([^"]*)" \(', s)
            if m:
                stack.append(live and self.expand(m.group(1)) == m.group(2))
                continue
            if s == ') else (':
                outer = all(stack[:-1])
                stack[-1] = outer and not stack[-1]
                continue
            if s == ')':
                stack.pop()
                continue
            if live:
                self.stmt(s)
        assert not stack, 'unbalanced ( ) in the block'
        return self


EXT, ASIDE = 'cam_ext.cfg', 'cam_ext.cfg.d3d9'


def _run(running, files, have_sc=True):
    return Box(running, files, have_sc).run(_block()['lines'])


