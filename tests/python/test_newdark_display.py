def test_thief2_carries_the_display_block_before_the_game_starts():
    pb = _block()
    assert pb['file'] == 'Play Thief 2.bat'
    assert pb['before'] == 'start "" Thief2.exe', (
        'the block must run BEFORE the game reads cam_ext.cfg')
    assert 'ND_DX6' in '\n'.join(pb['lines'])


def test_vcrkmd_box_gets_the_dx6_display():
    """.124's first launch after a sync: the library's cam_ext.cfg goes aside."""
    box = _run({'vcrmp'}, {EXT, 'cam.cfg'})
    assert EXT not in box.files and ASIDE in box.files
    assert box.env['ND_DX6'] == '1'


def test_vcrkmd_box_is_steady_on_the_next_launch():
    box = _run({'vcrmp'}, {ASIDE})
    assert box.files == {ASIDE}


def test_a_sync_that_restores_cam_ext_is_undone_at_the_next_launch():
    """GAMESYNC never deletes and does restore a missing file, so on the vcr-kmd
    box both can exist; `move /y` must replace the old aside copy."""
    box = _run({'vcrmp'}, {EXT, ASIDE})
    assert box.files == {ASIDE}


def test_every_other_gpu_keeps_direct3d_9_untouched():
    """A GeForce/Radeon/Intel box must not have its file moved or rewritten."""
    for running in (set(), {'nv4', 'ati2mtag', 'ialm'}):
        box = _run(running, {EXT})
        assert box.files == {EXT}, running
        assert box.env['ND_DX6'] == '0'


def test_the_file_comes_back_when_the_driver_changes():
    """Two-way, like glide_swap: after a rollback to the vendor driver (the
    vcrmp key stays, the miniport no longer runs) Direct3D 9 returns."""
    box = _run(set(), {ASIDE})
    assert box.files == {EXT}


def test_a_box_with_both_keeps_the_library_file():
    box = _run(set(), {EXT, ASIDE})
    assert EXT in box.files


def test_a_probe_that_cannot_run_is_the_librarys_own_behaviour():
    """No sc.exe (or any probe failure) must mean Direct3D 9 - the status quo -
    never the DX6 fallback. No box may be made worse by a failed probe."""
    box = _run({'vcrmp'}, {EXT}, have_sc=False)
    assert box.files == {EXT} and box.env['ND_DX6'] == '0'


def test_the_test_is_the_running_service_not_its_key():
    """A rollback leaves Services\\vcrmp behind with the device bound to the
    vendor driver; a key-presence test would keep that box on DX6 forever."""
    text = '\n'.join(_block()['lines'])
    assert re.search(r'^sc query vcrmp .*find /i "RUNNING"', text, re.M)
    assert 'reg query' not in text.lower()
    assert text.index('set ND_DX6=0') < text.index('sc query')


def test_the_block_is_plain_cmd():
    """The repo-wide traps: no doubled percent outside a for loop, no
    parentheses inside a value that cmd.exe expands in a block."""
    for line in _block()['lines']:
        assert not re.search(r'%%[A-Za-z_]', line), line
        if not line.lower().startswith('rem '):
            body = line.strip()
            assert body.count('(') <= 1 and body.count(')') <= 1, line


def test_staging_the_block_is_idempotent_and_refreshable(tmp_path):
    """post_block inserts it once, skips it when current, and a changed recipe
    replaces an older copy in place instead of stacking a second one."""
    t = tmp_path / 'Thief2'
    t.mkdir()
    launcher = ('@echo off\r\ncall "%~dp0FLEETRES.BAT"\r\n'
                'cd /d "%~dp0"\r\nstart "" Thief2.exe\r\nexit\r\n')
    (t / 'Play Thief 2.bat').write_bytes(launcher.encode('latin1'))
    pb = _block()
    r = sf.Runner(str(tmp_path), False, False)
    r.post_block(str(t), 'Thief2', pb)
    once = (t / 'Play Thief 2.bat').read_bytes().decode('latin1')
    assert once.count('set ND_DX6=0') == 1
    assert once.index('set ND_DX6=0') < once.index('start "" Thief2.exe')
    assert '\r\n' in once and '\n' not in once.replace('\r\n', '')
    r.post_block(str(t), 'Thief2', pb)
    assert (t / 'Play Thief 2.bat').read_bytes().decode('latin1') == once
    # an older version of the block (its first line intact) is refreshed
    stale = once.replace('move /y "%~dp0cam_ext.cfg" "%~dp0cam_ext.cfg.d3d9" >nul',
                         'rem an older body')
    (t / 'Play Thief 2.bat').write_bytes(stale.encode('latin1'))
    r.post_block(str(t), 'Thief2', pb)
    assert (t / 'Play Thief 2.bat').read_bytes().decode('latin1') == once


# ---------------------------------------------------------------------------
# the library the block relies on (skips LOUDLY when the share is absent)
# ---------------------------------------------------------------------------
def _lib_file(name):
    """case-insensitive: the tree ships USER.CFG and cam.cfg side by side"""
    if not os.path.isdir(THIEF2):
        pytest.skip('library not mounted at %s - the share-side NewDark checks '
                    'did NOT run; this is not a pass' % LIB)
    for n in os.listdir(THIEF2):
        if n.lower() == name.lower():
            return os.path.join(THIEF2, n)
    return None


def _active(path, var):
    """lines that DEFINE var (Dark config: a var is on by being present)"""
    if not path:
        return []
    with open(path, 'rb') as fh:
        text = fh.read().decode('latin1')
    return [l for l in text.splitlines()
            if re.match(r'\s*%s(\s|$)' % re.escape(var), l, re.I)]


def test_moving_cam_ext_aside_really_leaves_dx6_at_16_bpp():
    """The block works only because the Direct3D 9 switches live in
    cam_ext.cfg ALONE. If one of them moves into a file the game always
    reads, the fallback stops falling back - silently."""
    assert _active(_lib_file('cam_ext.cfg'), 'use_d3d_display'), (
        'cam_ext.cfg no longer enables use_d3d_display - re-check the block')
    for cfg in ('cam.cfg', 'user.cfg', 'dark.cfg', 'darkinst.cfg', 'install.cfg'):
        path = _lib_file(cfg)
        for var in ('use_d3d_display', 'force_32bit', 'force_32bit_textures'):
            assert not _active(path, var), (
                '%s defines %s: moving cam_ext.cfg aside no longer gives a '
                'vcr-kmd box the 16 bpp DX6 display' % (cfg, var))
    depth = _active(_lib_file('cam.cfg'), 'game_screen_depth')
    assert depth and depth[-1].split()[1] == '16', depth


def test_the_staged_exe_is_the_one_that_was_analysed():
    """The addresses and the conclusion come from one build. A new NewDark
    means re-running evidence/newdark_thief2/newdark_dis.py, not trusting it."""
    exe = _lib_file('Thief2.exe')
    assert exe, 'Thief2.exe missing from the staged tree'
    with open(exe, 'rb') as fh:
        md5 = hashlib.md5(fh.read()).hexdigest()
    assert md5 == ANALYSED_MD5, (
        'staged Thief2.exe is %s, the display analysis read %s - re-derive it '
        '(voodoo-cleanroom/vcr-kmd/evidence/newdark_thief2/newdark_dis.py)'
        % (md5, ANALYSED_MD5))


class _StuckBox(Box):
    """A box where the move cannot happen (a read-only cam_ext.cfg.d3d9 left
    by hand blocks `move /y`)."""
    def stmt(self, s):
        if s.strip().startswith('move /y'):
            return
        super().stmt(s)


def test_a_failed_move_is_written_down_not_swallowed():
    b = _StuckBox({"vcrmp"}, {EXT}).run(_block()["lines"])
    assert EXT in b.files and "nd_dx6-error.txt" in b.files


def test_a_move_that_worked_leaves_no_error_file_even_a_stale_one():
    b = _run({"vcrmp"}, {EXT, "nd_dx6-error.txt"})
    assert ASIDE in b.files and EXT not in b.files
    assert "nd_dx6-error.txt" not in b.files


def test_a_d3d_box_never_gets_an_error_file():
    b = _run(set(), {EXT})
    assert "nd_dx6-error.txt" not in b.files and EXT in b.files
