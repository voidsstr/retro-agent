TEST(the_w386_flags_are_found_by_walking_the_sections)
{
    CHECK_EQ_I(piff_w386_flags_offset(f19_pif, sizeof(f19_pif)), 0x1AD);
    CHECK_EQ_U(f19_pif[0x1AD], 0x02);          /* background, NOT full screen */
}

TEST(the_shell_written_pif_is_set_full_screen_once)
{
    unsigned char b[967];
    memcpy(b, f19_pif, sizeof(b));
    CHECK_EQ_I(piff_set_fullscreen(b, sizeof(b)), 1);
    CHECK_EQ_U(b[0x1AD], 0x0A);                /* 0x00021002 -> 0x0002100A */
    CHECK(memcmp(b, f19_pif, 0x1AD) == 0 && memcmp(b + 0x1AE, f19_pif + 0x1AE, sizeof(b) - 0x1AE) == 0,
          "only that one byte may change");
    CHECK_EQ_I(piff_set_fullscreen(b, sizeof(b)), 0);  /* already set: leave the file alone */
    CHECK_EQ_U(b[0x1AD], 0x0A);
}

TEST(a_file_that_is_not_a_pif_this_knows_is_left_alone)
{
    unsigned char b[967];
    memcpy(b, f19_pif, sizeof(b));
    CHECK_EQ_I(piff_set_fullscreen(b, 0x171), -1);              /* truncated */
    b[0x171] = 'X';                                              /* no MICROSOFT PIFEX */
    CHECK_EQ_I(piff_set_fullscreen(b, sizeof(b)), -1);
    memcpy(b, f19_pif, sizeof(b));
    b[0x187] = 'X';                                              /* no W386 section */
    CHECK_EQ_I(piff_w386_flags_offset(b, sizeof(b)), -1);
    memcpy(b, f19_pif, sizeof(b));
    b[0x171 + 16] = 0x71; b[0x171 + 17] = 0x01;                  /* next points at itself */
    CHECK_EQ_I(piff_w386_flags_offset(b, sizeof(b)), -1);
    memcpy(b, f19_pif, sizeof(b));
    b[0x187 + 20] = 0x08; b[0x187 + 21] = 0;                     /* W386 data too short */
    CHECK_EQ_I(piff_w386_flags_offset(b, sizeof(b)), -1);
    CHECK_EQ_I(piff_set_fullscreen(NULL, 967), -1);
}

TEST(the_w386_section_is_not_assumed_at_a_fixed_offset)
{
    /* Move the whole WINDOWS 386 3.0 section 0x20 bytes later and repoint the
     * chain: the flags must be found at their new place, not at 1ADh. */
    unsigned char b[1024];
    memset(b, 0, sizeof(b));
    memcpy(b, f19_pif, 0x187);                              /* basic + PIFEX heading */
    memcpy(b + 0x1A7, f19_pif + 0x187, 0x7E);                /* W386 heading + data */
    b[0x171 + 16] = 0xA7; b[0x171 + 17] = 0x01;             /* PIFEX next -> 1A7h */
    b[0x1A7 + 16] = 0xFF; b[0x1A7 + 17] = 0xFF;             /* last section */
    b[0x1A7 + 18] = 0xBD; b[0x1A7 + 19] = 0x01;             /* data at 1BDh */
    CHECK_EQ_I(piff_w386_flags_offset(b, sizeof(b)), 0x1CD);
}

TEST(only_a_pif_name_is_touched)
{
    CHECK_EQ_I(piff_is_pif_name("C:\\WINDOWS\\Desktop\\Doom.pif"), 1);
    CHECK_EQ_I(piff_is_pif_name("C:\\WINDOWS\\Desktop\\DOOM.PIF"), 1);
    CHECK_EQ_I(piff_is_pif_name("C:\\WINDOWS\\Desktop\\Quake II.lnk"), 0);
    CHECK_EQ_I(piff_is_pif_name("pif"), 0);
    CHECK_EQ_I(piff_is_pif_name(NULL), 0);
}

